#!/usr/bin/env python3
"""ნეიტრალური ზოლი: data/no_mans_land.json → rules/no-mans-land.md

გაშვება:  python3 tools/build_no_mans_land.py   (ბილდერისთვის data.js-ს tools/build_builder.py აწყობს)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "<!-- ავტომატურად გენერირებული: tools/build_no_mans_land.py — შეცვალე data/no_mans_land.json -->\n"
DANGER = "★"


def load():
    return json.loads((ROOT / "data" / "no_mans_land.json").read_text(encoding="utf-8"))


def mod(z):
    if z["search_mod"] is None:
        return "ძებნა არ შეიძლება"
    return f"+{z['search_mod']}" if z["search_mod"] else "±0"


def main():
    d = load()
    beasts = {b["id"]: b for b in d["beasts"]}
    out = [HEADER, "# ნეიტრალური ზოლი", "",
           "> სანგრებს შორის მიწა — არავისი და ყველასი. აქ იბრძვიან მცირე რაზმები: ზვერავენ, ტყვეებს ათავისუფლებენ, ურჩხულის ძვლებს და",
           "> ბეჭდის ნამსხვრევებს ეძებენ. ლორი — `../lore/01-general-lore.md`; მონაცემები — `../data/no_mans_land.json`.", "",
           "**როგორ ვთამაშობთ:** ბრძოლის წინ აირჩიე (ან d10-ით აგორე) **ზონა** — ის განსაზღვრავს რელიეფს, ერთ სპეციალურ წესს და მოხეტიალე ურჩხულს.",
           "დაფაზე დადე **3 ძებნის მარკერი** (შუაში და ორ გვერდზე). ღამის ბრძოლაში ყოველი რაუნდის დასაწყისში აგორე **ღამის ცხრილი**.",
           "ბრძოლებს შორის კამპანიაში შეგიძლია **დაზვერვაზე** გაგზავნო მზვერავები.", "",
           "## ზონები", "",
           "| d10 | ზონა | საფრთხე | ძებნა | ზონის ნაპოვნი | მოხეტიალე ურჩხული |", "|---|---|---|---|---|---|"]
    for i, z in enumerate(d["zones"]):
        rolls = f"{i + 1}" if i < 8 else ""
        find = z["find"]["name"] if z["find"] else "—"
        out.append(f"| {rolls} | **{z['name']}** | {DANGER * z['danger']} | {mod(z)} | {find} | {beasts[z['monster']]['name']} |")
    out += ["| 9–10 | თავად აირჩიე | | | | |", ""]
    for z in d["zones"]:
        out += [f"### {z['name']}", "", f"*{z['terrain']}*", "", f"- **წესი:** {z['rule']}"]
        if z["find"]:
            out.append(f"- **ზონის ნაპოვნი:** {z['find']['name']}")
        out += ["", z["lore"], ""]
    out += ["## ძებნა", "",
            "მოდელს, რომელიც აქტივაციას ძებნის მარკერის 1\"-ში იწყებს, სროლის ნაცვლად **ძებნა** შეუძლია: d10 + ზონის მოდიფიკატორი (მაქს. 10).",
            "ბუნებრივი **1** — ყოველთვის ხაფანგია. ერთი მარკერი ერთხელ იძებნება. მზვერავს (ნიშანი „მზვერავი“) +1.", "",
            "| d10 | შედეგი | რა ხდება |", "|---|---|---|"]
    out += [f"| {s['roll']} | **{s['name']}** | {s['text']} |" for s in d["search"]]
    out += ["", "## ღამის ცხრილი", "", "ღამის ან ნისლის სცენარში — ყოველი რაუნდის დასაწყისში (დღისით — მხოლოდ პირველ რაუნდში).", "",
            "| d10 | მოვლენა | რა ხდება |", "|---|---|---|"]
    out += [f"| {n['roll']} | **{n['name']}** | {n['text']} |" for n in d["night"]]
    out += ["", "## მოხეტიალე ურჩხულები", "", d["monster_rules"], "",
            "| ურჩხული | რაოდ. | მოძ | ხჩ | ჯავ | სიც | ნებ | შეტევა | წესი |", "|---|---|---|---|---|---|---|---|---|"]
    out += [f"| **{b['name']}** | {b['count']} | {b['move']}\" | {b['melee']} | {b['armor']} | {b['wounds']} | {b['nerve']} | {b['attack']} | {b['rule']} |"
            for b in d["beasts"]]
    out += ["", "## დაზვერვა (კამპანია, ბრძოლებს შორის)", "",
            "ბრძოლებს შორის **2-მდე** მოდელი (არა ლიდერი, არა დაჭრილი) შეიძლება ნეიტრალურ ზოლში გაგზავნო. აირჩიე ზონა და აგორე",
            "**d10 + 1 (მზვერავი) + 1 (ჩასაფრება) + 1 (შენი ზონა) − ზონის საფრთხე + 2**. ბილდერის „კამპანიის“ ჩანართი ამას თავისით ითვლის.", "",
            "| შედეგი | რა ხდება |", "|---|---|"]
    for r in d["raid"]:
        lo = "≤" + str(r["max"]) if r["min"] < -50 else (f"{r['min']}+" if r["max"] > 50 else f"{r['min']}–{r['max']}")
        out.append(f"| {lo} | **{r['name']}:** {r['text']} |")
    out += ["", f"**ზონის კონტროლი:** {d['control']}", "",
            "## სცენარების იდეები", "",
            "- **ღამის რეიდი:** 6 რაუნდი, ღამე; 3 ძებნის მარკერი; ვინც მეტ მარკერს გაჩხრეკს და თავის კიდემდე მიიტანს.",
            "- **გალიები უღლის კვალზე:** ნათელი მხარე გალიებს ხსნის (ყოველი ღია გალია — ტყვე, რომელიც კიდემდე უნდა გაიყვანოს), ბნელი იცავს.",
            "- **ძვლების ბაზარი:** ორივე რაზმი ძვლების ველზე; მოხეტიალე ურჩხული ყოველ რაუნდში d10 1–3-ზე ჩნდება.",
            "- **ნამსხვრევი კიდეზე:** ერთი მარკერი ჭრილობის კიდეზე; ნათელი მხარე მას ქვის ქვეშ ტოვებს (ადგილზე 2 რაუნდი), ბნელი — მიაქვს.",
            "", "⚠️ ნეიტრალურ ზოლში მშვიდობიანი მოსახლეობა არ არის: სოფლები დიდი ხანია ცარიელია, და მათი მცხოვრებლები სცენარის მიზანი ვერ იქნება.", ""]
    (ROOT / "rules" / "no-mans-land.md").write_text("\n".join(out), encoding="utf-8")
    print(f"rules/no-mans-land.md: {len(d['zones'])} ზონა")


if __name__ == "__main__":
    main()
